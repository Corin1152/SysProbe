import Foundation

/// 主线程的「让路」判据：现在是不是正在滚动。
///
/// ── 为什么需要它 ────────────────────────────────────────────────────────────
///
/// 采样定时器挂在 `.default` 模式上，UIScrollView 一开始拖动就把 run loop 切到
/// tracking 模式 —— **定时器**那一下确实让路了。但每一拍的读取都派发到后台队列，
/// 结果几十到几百毫秒之后才由 `Task { @MainActor }` 贴回主线程，而**这一贴不受
/// run loop 模式约束**：主队列的 source 注册在 common modes 下，tracking 期间照跑。
///
/// 于是那一贴正好落在滚动的某几帧里 —— 而每次贴都会 `@Published` 一次，把整页 body
/// 重算一遍（四个分页都在 `TabView` 里活着，电源页还带一张图）。掉帧就是这么来的，
/// 而且它解释了一个看起来矛盾的现象：定时器明明「让路」了，滚动照样卡。
///
/// 所以在「贴回主线程」这一步再判一次：正在滚动就**丢掉这一拍**，下一拍再补。
/// 与定时器让路是同一个取向，只是把闸门从「排下一拍」挪到了「应用结果」。
///
/// ── 为什么放在 `Shared/Hardware` ────────────────────────────────────────────
///
/// 因为这一层同时被主 App 与负一屏扩展编译进去（见 `project.yml` 的 sources），
/// 而两个宿主都在跑 `HardwareMonitor` / `PowerMonitor`。放在这里不用动工程文件，
/// 也不会出现「扩展那边找不到符号」。
///
/// ── 判据失效时是安全的 ──────────────────────────────────────────────────────
///
/// `RunLoop.Mode.tracking` 就是 UIKit 滚动期间那个 run loop 模式。万一将来某个系统
/// 版本上这条判据不再成立，结果是「让路不生效」—— 退回今天的行为，不会出错；
/// 万一误判成「正在滚动」，代价也只是这一拍不更新，一秒后下一拍就补上。
/// 两个方向都不需要额外的兜底。
enum MainThreadPacing {

    /// 主线程此刻被 UIScrollView 的拖动 / 惯性滚动占着吗。
    ///
    /// **只能在主线程读** —— 它读的是主 run loop 的当前模式。本工程默认
    /// `SWIFT_DEFAULT_ACTOR_ISOLATION = MainActor`，所以下面这些调用点天然满足；
    /// 将来若从非主线程调用，请先跳回主 actor。
    static var isScrolling: Bool {
        RunLoop.main.currentMode == .tracking
    }
}
